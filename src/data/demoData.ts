// Helper to generate elegant local SVG data URLs with natural color palettes
function createSvgDataUrl(title: string, subtitle: string, bgGradient: [string, string], accentColor: string, isVideo = false): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 800 600" width="800" height="600">
    <defs>
      <linearGradient id="grad" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgGradient[0]}"/>
        <stop offset="100%" stop-color="${bgGradient[1]}"/>
      </linearGradient>
      <pattern id="grain" width="40" height="40" patternUnits="userSpaceOnUse">
        <circle cx="20" cy="20" r="1" fill="#FFFFFF" opacity="0.15"/>
      </pattern>
    </defs>
    <rect width="800" height="600" fill="url(#grad)"/>
    <rect width="800" height="600" fill="url(#grain)"/>
    
    <!-- Editorial frame lines -->
    <rect x="30" y="30" width="740" height="540" fill="none" stroke="${accentColor}" stroke-width="1.5" opacity="0.4"/>
    
    <!-- Visual composition geometric accents -->
    <circle cx="680" cy="120" r="80" fill="${accentColor}" opacity="0.2"/>
    <circle cx="160" cy="460" r="140" fill="${bgGradient[1]}" opacity="0.25"/>
    <rect x="80" y="80" width="120" height="120" rx="8" fill="${accentColor}" opacity="0.15"/>
    
    ${isVideo ? `
      <!-- Video Play Icon overlay -->
      <circle cx="400" cy="280" r="48" fill="#FFFFFF" opacity="0.85"/>
      <polygon points="390,260 420,280 390,300" fill="${bgGradient[0]}"/>
    ` : ''}

    <!-- Content Labels -->
    <g transform="translate(60, ${isVideo ? 430 : 410})">
      <rect x="0" y="0" width="440" height="85" rx="6" fill="#FFFFFF" opacity="0.85"/>
      <text x="24" y="36" font-family="-apple-system, BlinkMacSystemFont, Segoe UI, sans-serif" font-size="22" font-weight="600" fill="#242822">
        ${title}
      </text>
      <text x="24" y="64" font-family="-apple-system, BlinkMacSystemFont, Segoe UI, sans-serif" font-size="14" font-weight="400" fill="#5A6056">
        ${subtitle} [Demo Fixture]
      </text>
    </g>
  </svg>`;

  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

